#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

const rootDir = path.join(__dirname, '..');
const packageJson = require(path.join(rootDir, 'package.json'));
const version = packageJson.version;

const swiftPath = path.join(rootDir, 'ios', 'ApphudSdkVersion.swift');
const swiftContents = `// Generated by scripts/sync-sdk-version.js from package.json — do not edit manually.

enum ApphudSdkVersion {
  static let value = "${version}"
}
`;

fs.writeFileSync(swiftPath, swiftContents, 'utf8');
console.log(`Synced RN Apphud SDK version ${version} -> ios/ApphudSdkVersion.swift`);
